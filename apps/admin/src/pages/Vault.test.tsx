import { ApiError } from '@better-forge/ui'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { api } from '../api/client'
import VaultPage from './Vault'

vi.mock('../api/client', () => ({ api: { get: vi.fn(), post: vi.fn(), patch: vi.fn(), delete: vi.fn() } }))
const vault = { id: 1, name: 'Operations', type: 'local' }
const secret = { id: 2, vaultId: 1, name: 'Token', type: 'value', version: 3 }
function setup() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  render(<QueryClientProvider client={client}><VaultPage /></QueryClientProvider>)
  return userEvent.setup()
}
beforeEach(() => {
  vi.resetAllMocks()
  vi.mocked(api.get).mockImplementation(async path => path === '/admin/vaults' ? [vault] : [secret])
})
describe('Vault', () => {
  it('creates a local vault and a secret without exposing the value', async () => {
    const user = setup()
    await user.click(await screen.findByRole('button', { name: 'Create vault' }))
    const dialog = screen.getByRole('dialog')
    await user.type(within(dialog).getByLabelText('Vault name'), 'New vault')
    vi.mocked(api.post).mockResolvedValueOnce(vault)
    await user.click(within(dialog).getByRole('button', { name: 'Create Vault' }))
    await waitFor(() => expect(api.post).toHaveBeenCalledWith('/admin/vaults', { name: 'New vault', type: 'local' }))
    await user.click(await screen.findByRole('button', { name: 'New Secret' }))
    const form = screen.getByRole('dialog')
    await user.type(within(form).getByLabelText('Secret name'), 'Key')
    await user.type(within(form).getByLabelText('Value'), 'confidential')
    vi.mocked(api.post).mockResolvedValueOnce({})
    await user.click(within(form).getByRole('button', { name: 'Save Secret' }))
    await waitFor(() => expect(api.post).toHaveBeenCalledWith('/admin/vaults/1/secrets', { name: 'Key', type: 'value', value: 'confidential' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(screen.queryByText('confidential')).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Reveal' })).not.toBeInTheDocument()
  })
  it('rotates with the current version and reports failures without echoing secret data', async () => {
    const user = setup()
    await user.click(await screen.findByRole('button', { name: 'Operations' }))
    expect(screen.getByText(/Available integrations depend on deployment settings/)).toBeInTheDocument()
    expect(screen.queryByText(/Monitor authentication and notification channels are not yet available/)).not.toBeInTheDocument()
    expect(screen.getByText(/Secret values cannot be revealed/)).toBeInTheDocument()
    await user.click(await screen.findByRole('button', { name: 'Rotate Token' }))
    const dialog = screen.getByRole('dialog')
    await user.type(within(dialog).getByLabelText('Value'), 'replacement')
    vi.mocked(api.patch).mockRejectedValueOnce(new Error('replacement'))
    await user.click(within(dialog).getByRole('button', { name: 'Rotate Secret' }))
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('Could not save secret')
    expect(within(dialog).getByRole('alert')).not.toHaveTextContent('replacement')
    vi.mocked(api.patch).mockResolvedValueOnce({})
    await user.click(within(dialog).getByRole('button', { name: 'Rotate Secret' }))
    await waitFor(() => expect(api.patch).toHaveBeenLastCalledWith('/admin/vaults/1/secrets/2', { version: 3, value: 'replacement' }))
  })
  it('saves username/password and JSON using the upstream request format', async () => {
    const user = setup()
    await user.click(await screen.findByRole('button', { name: 'Operations' }))
    await user.click(await screen.findByRole('button', { name: 'New Secret' }))
    let dialog = screen.getByRole('dialog')
    await user.type(within(dialog).getByLabelText('Secret name'), 'Login')
    await user.selectOptions(within(dialog).getByLabelText('Type'), 'userpass')
    await user.type(within(dialog).getByLabelText('Username'), 'account')
    await user.type(within(dialog).getByLabelText('Password'), 'password')
    vi.mocked(api.post).mockResolvedValueOnce({})
    await user.click(within(dialog).getByRole('button', { name: 'Save Secret' }))
    await waitFor(() => expect(api.post).toHaveBeenCalledWith('/admin/vaults/1/secrets', { name: 'Login', type: 'userpass', userpass: { username: 'account', password: 'password' } }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    await user.click(screen.getByRole('button', { name: 'New Secret' }))
    dialog = screen.getByRole('dialog')
    await user.type(within(dialog).getByLabelText('Secret name'), 'Config')
    await user.selectOptions(within(dialog).getByLabelText('Type'), 'json')
    await user.click(within(dialog).getByLabelText('JSON object'))
    await user.paste('{"key":"value"}')
    vi.mocked(api.post).mockResolvedValueOnce({})
    await user.click(within(dialog).getByRole('button', { name: 'Save Secret' }))
    await waitFor(() => expect(api.post).toHaveBeenLastCalledWith('/admin/vaults/1/secrets', { name: 'Config', type: 'json', json: '{"key":"value"}' }))
  })
  it('reloads a secret after a concurrent rotation prevents deletion', async () => {
    const user = setup()
    await user.click(await screen.findByRole('button', { name: 'Operations' }))
    await user.click(await screen.findByRole('button', { name: 'Delete secret Token' }))
    vi.mocked(api.delete).mockRejectedValueOnce(new ApiError('Conflict', 409))
    await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Delete' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Secret changed')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await waitFor(() => expect(vi.mocked(api.get).mock.calls.filter(([path]) => path === '/admin/vaults/1/secrets').length).toBeGreaterThan(1))
  })
  it('validates JSON and confirms deletion', async () => {
    const user = setup()
    await user.click(await screen.findByRole('button', { name: 'Operations' }))
    await user.click(await screen.findByRole('button', { name: 'New Secret' }))
    let dialog = screen.getByRole('dialog')
    await user.type(within(dialog).getByLabelText('Secret name'), 'Settings')
    await user.selectOptions(within(dialog).getByLabelText('Type'), 'json')
    await user.type(within(dialog).getByLabelText('JSON object'), 'invalid')
    await user.click(within(dialog).getByRole('button', { name: 'Save Secret' }))
    expect(within(dialog).getByRole('alert')).toHaveTextContent('valid JSON object')
    expect(api.post).not.toHaveBeenCalled()
    await user.click(within(dialog).getByRole('button', { name: 'Cancel' }))
    await user.click(await screen.findByRole('button', { name: 'Delete secret Token' }))
    dialog = screen.getByRole('dialog')
    expect(within(dialog).getByText(/references will stop working/)).toBeInTheDocument()
    vi.mocked(api.delete).mockResolvedValueOnce(undefined)
    await user.click(within(dialog).getByRole('button', { name: 'Delete' }))
    await waitFor(() => expect(api.delete).toHaveBeenCalledWith('/admin/vaults/1/secrets/2', { version: 3 }))
  })
})
